def ensure_gradle_property(path: Path, key: str, value: str) -> bool:
    if not path.exists():
        return False
    old = path.read_text(encoding="utf-8")
    lines = old.splitlines()
    changed = False
    found = False
    for idx, line in enumerate(lines):
        if line.strip().startswith("#"):
            continue
        if re.match(rf"\s*{re.escape(key)}\s*=", line):
            found = True
            new_line = f"{key}={value}"
            if line != new_line:
                lines[idx] = new_line
                changed = True
            break
    if not found:
        if lines and lines[-1].strip():
            lines.append("")
        lines.append(f"{key}={value}")
        changed = True
    if not changed:
        return False
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return True


def patch_variables_gradle(path: Path) -> bool:
    if not path.exists():
        return False
    old = path.read_text(encoding="utf-8")
    new = old
    for key, value in ANDROIDX_COMPAT_VERSIONS.items():
        new = re.sub(
            rf"({re.escape(key)}\s*=\s*)'[^']+'",
            rf"\1'{value}'",
            new,
        )
    if new == old:
        return False
    path.write_text(new, encoding="utf-8")
    return True


def android_no_compress_exts() -> list[str]:
    exts = list(ANDROID_STARTUP_NO_COMPRESS_EXTS)
    if os.environ.get("PVNM_ANDROID_NO_COMPRESS_NPY", "").lower() in ("1", "true", "yes", "on"):
        exts.append("npy")
    extra = os.environ.get("PVNM_ANDROID_NO_COMPRESS_EXTRA", "")
    for raw in extra.split(","):
        value = raw.strip().lstrip(".")
        if value:
            exts.append(value)
    result: list[str] = []
    seen: set[str] = set()
    for ext in exts:
        key = ext.lower()
        if key not in seen:
            seen.add(key)
            result.append(key)
    return result


def patch_app_no_compress(path: Path) -> bool:
    if not path.exists():
        return False
    old = path.read_text(encoding="utf-8")
    exts = android_no_compress_exts()
    ext_list = "[" + ", ".join(f"'{ext}'" for ext in exts) + "]"
    marker_start = "    // PVNM startup noCompress START"
    marker_end = "    // PVNM startup noCompress END"
    block = f"""    // PVNM startup noCompress START
    androidResources {{
        noCompress += {ext_list}
    }}
    // PVNM startup noCompress END
"""
    pattern = re.compile(
        rf"\n?{re.escape(marker_start)}.*?{re.escape(marker_end)}\n?",
        re.DOTALL,
    )
    if marker_start in old:
        new = pattern.sub("\n" + block, old)
    elif "    buildTypes {" in old:
        new = old.replace("    buildTypes {", block + "\n    buildTypes {", 1)
    else:
        insert_at = old.rfind("\n}")
        if insert_at < 0:
            return False
        new = old[:insert_at] + "\n" + block + old[insert_at:]
    if new == old:
        return False
    path.write_text(new, encoding="utf-8")
    return True


