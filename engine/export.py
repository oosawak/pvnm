def _collect_asset_files(script: dict, endings: list | None = None) -> set[str]:
    """スクリプト/エンディングから参照されるファイルパスを収集する。"""
    files: set[str] = set()
    for scene in script.get("scenes", []):
        # 背景画像
        v = scene.get("bg", "")
        if v:
            files.add(v)
        # キャラクター画像
        for slot in ("char_l", "char_c", "char_r"):
            cfg = scene.get(slot, {})
            if isinstance(cfg, dict):
                f = cfg.get("file", "")
                if f:
                    files.add(f)
                for ff in cfg.get("anim", {}).get("flipbook_files", []):
                    if ff:
                        files.add(ff)
        # パレットファイル
        pf = scene.get("palette_file", "")
        if pf:
            files.add(pf)
        # フォントファイル
        ff = scene.get("font_file", "")
        if ff:
            files.add(ff)
        # オーディオファイル
        for akey in ("bgm_file", "se_file"):
            af = scene.get(akey, "")
            if af:
                files.add(af)
    for ending in endings or []:
        if not isinstance(ending, dict):
            continue
        bgm = ending.get("bgm_file", "")
        if bgm:
            files.add(bgm)
        for slide in ending.get("slides", []) or []:
            if isinstance(slide, dict):
                img = slide.get("image", "")
                if img:
                    files.add(img)
    return files


def _collect_title_asset_files(title_config: dict | None = None) -> set[str]:
    """タイトル画面設定から参照される画像/BGMパスを収集する。"""
