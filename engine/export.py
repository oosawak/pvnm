def _resolve_export_persistent(scene: dict, persistent_bg,
                               persistent_chars: dict) -> tuple:
    """Mirror VNPlayer's BG/character inherit rules for export prebuild."""
    bg = copy.deepcopy(persistent_bg)
    chars = {
        k: (None if v is None else copy.deepcopy(v))
        for k, v in (persistent_chars or {}).items()
    }
    for cfg in chars.values():
        prepare_char_config_for_next_scene(cfg)
    if scene.get("bg_hide"):
        bg = None
    else:
        bg_path = scene.get("bg", "") or ""
        if bg_path:
            bg = {
                "path": bg_path,
                "fullscreen": bool(scene.get("bg_fullscreen", False)),
                "above_dialog": bool(scene.get("bg_above_dialog", False)),
                "anim": scene.get("bg_anim", {}) or {},
            }
    for slot_key in ("char_l", "char_c", "char_r"):
        cfg = scene.get(slot_key, {})
        if not isinstance(cfg, dict):
            cfg = {}
        if cfg.get("hide"):
            chars[slot_key] = None
            continue
        f = cfg.get("file", "") or ""
        if f:
            chars[slot_key] = copy.deepcopy(cfg)
    return bg, chars


def _persistent_image_paths(persistent_bg, persistent_chars: dict) -> list:
    paths: list = []
    if persistent_bg:
        bp = persistent_bg.get("path", "")
        if bp:
            paths.append(bp)
        for fb in (persistent_bg.get("anim", {}) or {}).get(
                "flipbook_files", []) or []:
            if fb:
                paths.append(fb)
    for cfg in (persistent_chars or {}).values():
        if not cfg:
            continue
        f = cfg.get("file", "")
        if f:
            paths.append(f)
        for fb in (cfg.get("anim", {}) or {}).get(
                "flipbook_files", []) or []:
            if fb:
                paths.append(fb)
    return paths


def _prebuild_persistent_images(add_image, record_source_size,
                                src_base: str, persistent_bg,
                                persistent_chars: dict, pal,
                                hide_dialog: bool,
                                source_size_func=None) -> None:
    source_size = source_size_func or (
        lambda path: _source_image_size(path, src_base))
    if persistent_bg:
        bg_path = persistent_bg.get("path", "")
        if bg_path:
            src_size = source_size(bg_path)
            record_source_size(bg_path, pal, src_size)
            if src_size[0] > 0 and src_size[1] > 0:
                sw, sh = _export_bg_display_size(
                    src_size[0], src_size[1], persistent_bg, hide_dialog)
                files = [bg_path]
                files.extend((persistent_bg.get("anim", {}) or {}).get(
                    "flipbook_files", []) or [])
                for path in files:
                    if path:
                        record_source_size(path, pal, source_size(path))
                        add_image(path, sw, sh, pal, original=False)
    for cfg in (persistent_chars or {}).values():
        if not cfg:
            continue
        main_path = cfg.get("file", "") or ""
        if not main_path:
            continue
        src_size = source_size(main_path)
        record_source_size(main_path, pal, src_size)
        if src_size[0] <= 0 or src_size[1] <= 0:
            continue
        load_w, load_h = _export_sprite_cache_size(cfg, src_size)
        alpha_colkey = normalize_color_key(
            cfg.get("colkey", COLOR_KEY_AUTO)) == COLOR_KEY_AUTO
        add_image(main_path, load_w, load_h, pal, original=False,
                  alpha_colkey=alpha_colkey)
        for fb in (cfg.get("anim", {}) or {}).get(
                "flipbook_files", []) or []:
            if fb:
                record_source_size(fb, pal, source_size(fb))
                add_image(fb, load_w, load_h, pal, original=False,
                          alpha_colkey=alpha_colkey)


def _export_bg_display_size(iw: int, ih: int, bg_cfg: dict,
                            hide_dialog: bool) -> tuple[int, int]:
    if iw <= 0 or ih <= 0:
        return 1, 1
    above_dialog = bool(bg_cfg.get("above_dialog")) and not hide_dialog
    h_eff = _DIALOG_Y if above_dialog else _RUNTIME_H
    fit_scale = min(_RUNTIME_W / iw, h_eff / ih)
    if bg_cfg.get("fullscreen") or above_dialog:
        scale = fit_scale
    else:
        scale = min(1.0, fit_scale)
    return max(1, round(iw * scale)), max(1, round(ih * scale))


def _fit_size_within(iw: int, ih: int,
                     max_w: int, max_h: int) -> tuple[int, int]:
    if iw <= 0 or ih <= 0:
        return 1, 1
    scale = min(1.0, max_w / iw, max_h / ih)
    return max(1, round(iw * scale)), max(1, round(ih * scale))


def _export_sprite_cache_size(cfg: dict, src_size: tuple[int, int]) -> tuple[int, int]:
    w = int(cfg.get("w") or 0)
    h = int(cfg.get("h") or 0)
    if w > 0 and h > 0:
        return w, h
    if w > 0:
        return w, max(1, round(src_size[1] * w / src_size[0]))
    if h > 0:
        return max(1, round(src_size[0] * h / src_size[1])), h
    return _fit_size_within(src_size[0], src_size[1], _RUNTIME_W, _RUNTIME_H)


def _source_image_size(path: str, base_dir: str) -> tuple[int, int]:
    try:
        from PIL import Image
        abs_path = _existing_path_variant(
            path if os.path.isabs(path) else os.path.join(base_dir, path))
        if not abs_path:
            return 0, 0
        with Image.open(abs_path) as img:
            return int(img.width), int(img.height)
    except Exception:
        return 0, 0


def _copy_image_cache(src_base: str, dst_dir: str, asset_files: set[str],
                      dst_cache_name: str = ".pvnm_cache"):
    """Copy portable image cache entries into the exported app.

    ImageCache now uses relative project paths for v2 cache names, so those
    entries can be reused after export as long as assets keep the same relative
    layout. Old absolute-path cache files are intentionally skipped.
    """
    src_cache = os.path.join(src_base, ".pvnm_cache")
    if not os.path.isdir(src_cache):
        return
    wanted_prefixes = {
        "v2_" + hashlib.md5(
            _export_cache_key_path(path, src_base).encode("utf-8")
        ).hexdigest()[:12] + "_"
        for path in asset_files
    }
    dst_cache = os.path.join(dst_dir, dst_cache_name)
    copied = 0
    for name in os.listdir(src_cache):
        if not (name.startswith("v2_") and name.endswith(".npy")):
            continue
        if not any(name.startswith(prefix) for prefix in wanted_prefixes):
            continue
        src = os.path.join(src_cache, name)
        if not os.path.isfile(src):
            continue
        os.makedirs(dst_cache, exist_ok=True)
        shutil.copy2(src, os.path.join(dst_cache, name))
        copied += 1
    if copied:
        print(f"[export] bundled {copied} image cache files")
    return copied


