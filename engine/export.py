def _externalize_web_image_cache(app_dir: str, dst_cache_dir: str,
                                 url_prefix: str,
                                 runtime_report: dict | None = None) -> int:
    """Move prebuilt image cache files out of the pyxapp for faster Web start.

    The manifest stays inside the packaged app because the Python runtime needs
    it immediately. The heavy ``.npy`` files are copied beside the HTML and read
    on demand through a same-origin WebView/browser request.
    """
    manifest_path = os.path.join(app_dir, "image_manifest.json")
    try:
        with open(manifest_path, encoding="utf-8") as f:
            manifest = json.load(f)
    except Exception:
        return 0
    if not isinstance(manifest, dict):
        return 0
    cache_dir_name = str(manifest.get("cache_dir") or "pvnm_cache")
    src_cache_dir = os.path.join(app_dir, cache_dir_name)
    if not os.path.isdir(src_cache_dir):
        return 0

    copied = sum(
        1 for name in os.listdir(src_cache_dir)
        if name.endswith(".npy")
        and os.path.isfile(os.path.join(src_cache_dir, name))
    )
    _move_path_fast(src_cache_dir, dst_cache_dir)

    base_url = _quote_url_path(url_prefix)
    manifest["external_cache"] = {
        "kind": "same_origin",
        "base_url": base_url,
        "file_count": copied,
    }
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)

    if isinstance(runtime_report, dict):
        report = runtime_report.get("image_manifest")
        if isinstance(report, dict):
            report["external_cache"] = True
            report["external_cache_base"] = base_url
            report["external_cache_files"] = copied
            report["embedded_cache_files"] = 0
    if copied:
        print(f"[export] externalized {copied} image cache files")
    return copied


