def _merge_export_settings(settings: dict | None, proj_base: str) -> dict:
    """Return settings used by exported runtimes.

    EditorState intentionally does not own app-level UI settings such as
    speaker colors. Normal GUI exports pass them in, but worker/direct export
    paths can arrive here with an empty dict. In that case, fall back to the
    project-side settings.json so runtime text colors and reserved palette
    indices remain intact.
    """
    merged = _load_project_settings(proj_base)
    if isinstance(settings, dict):
        merged.update(settings)
    return merged


def _runtime_settings_log_stats(settings: dict | None) -> dict:
    if not isinstance(settings, dict):
        return {
            "dialog_role_count": 0,
            "speaker_count": 0,
            "speaker_palette_index_count": 0,
            "dialog_font_size": None,
        }
    roles = settings.get("dialog_role_indices")
    speaker_cfg = settings.get("speaker_colors")
    speakers = {}
    indices: set[int] = set()
    if isinstance(speaker_cfg, dict):
        narration = speaker_cfg.get("narration_text_color")
        if isinstance(narration, int):
            indices.add(narration)
        maybe_speakers = speaker_cfg.get("speakers")
        if isinstance(maybe_speakers, dict):
            speakers = maybe_speakers
            for entry in speakers.values():
                if not isinstance(entry, dict):
                    continue
                for key in ("name_color", "name_bg_color", "text_color"):
                    idx = entry.get(key)
                    if isinstance(idx, int):
                        indices.add(idx)
    return {
        "dialog_role_count": len(roles) if isinstance(roles, dict) else 0,
        "speaker_count": len(speakers),
        "speaker_palette_index_count": len(indices),
        "dialog_font_size": settings.get("dialog_font_size"),
    }


def _write_runtime_tree(state, app_dir: str, proj_base: str,
                        settings: dict, title: str,
                        package_label: str = ".pyxapp",
                        progress=None,
                        bundle_original_images: bool = True,
                        copy_audio_assets: bool = True,
                        pipeline_log=None,
                        script_override: dict | None = None,
                        endings_override: list | None = None,
                        asset_files_override: set[str] | None = None) -> dict:
    """Write the standalone player runtime tree into app_dir."""
    t_stage = time.perf_counter()
    _progress(progress, "Writing story data: building script")
    if pipeline_log:
        pipeline_log("runtime_tree.story_data.start")
    t_sub = time.perf_counter()
    script = script_override if script_override is not None else from_editor_state(state)
    if pipeline_log:
        script_counts = _script_quick_counts(script)
        pipeline_log(
            "runtime_tree.story_data.script_built",
            elapsed_sec=round(time.perf_counter() - t_sub, 4),
            **script_counts,
        )

    _progress(progress, "Writing story data: story.json compact")
    t_sub = time.perf_counter()
    story_path = os.path.join(app_dir, "story.json")
    _save_runtime_story_json(script, story_path)
    if pipeline_log:
        pipeline_log(
            "runtime_tree.story_data.story_json_written",
            elapsed_sec=round(time.perf_counter() - t_sub, 4),
            story_size=_safe_getsize(story_path),
            story_json_format="compact",
        )

    _progress(progress, "Writing story data: config normalize")
    t_sub = time.perf_counter()
    settings_path = os.path.join(app_dir, "settings.json")
    endings_path = os.path.join(app_dir, "endings.json")
    title_path = os.path.join(app_dir, "title_config.json")
    gallery_path = os.path.join(app_dir, "gallery_config.json")
    extra_text_path = os.path.join(app_dir, "extra_text_config.json")
    runtime_source_settings = _merge_export_settings(settings, proj_base)
    title_config = _normalize_title_config(getattr(state, "title_config", {}))
    gallery_config = normalize_gallery_config(
        getattr(state, "gallery_config", {}))
    extra_text_config = normalize_extra_text_config(
        getattr(state, "extra_text_config", {}))
    if pipeline_log:
        pipeline_log(
            "runtime_tree.story_data.configs_normalized",
            elapsed_sec=round(time.perf_counter() - t_sub, 4),
            ending_count=len(endings_override if endings_override is not None
                             else (getattr(state, "endings", []) or [])),
            gallery_page_count=len(gallery_config.get("pages", []) or []),
            extra_text_page_count=len(extra_text_config.get("pages", []) or []),
        )

    _progress(progress, "Writing story data: settings/endings")
    t_sub = time.perf_counter()
    runtime_settings = _write_runtime_json(
        state, runtime_source_settings, settings_path, endings_path)
    if pipeline_log:
        pipeline_log(
            "runtime_tree.story_data.runtime_json_written",
            elapsed_sec=round(time.perf_counter() - t_sub, 4),
            settings_size_initial=_safe_getsize(settings_path),
            endings_size=_safe_getsize(endings_path),
            source_settings=_runtime_settings_log_stats(
                runtime_source_settings),
            runtime_settings=_runtime_settings_log_stats(runtime_settings),
        )

    _progress(progress, "Writing story data: title/gallery/extra text")
    t_sub = time.perf_counter()
    with open(title_path, "w", encoding="utf-8") as f:
        json.dump(title_config, f, ensure_ascii=False, indent=2)
    with open(gallery_path, "w", encoding="utf-8") as f:
        json.dump(gallery_config, f, ensure_ascii=False, indent=2)
    with open(extra_text_path, "w", encoding="utf-8") as f:
        json.dump(extra_text_config, f, ensure_ascii=False, indent=2)
    runtime_settings.setdefault("storage_app_id", _storage_app_id(title))
    with open(settings_path, "w", encoding="utf-8") as f:
        json.dump(runtime_settings, f, ensure_ascii=False, indent=2)
    if pipeline_log:
        pipeline_log(
            "runtime_tree.story_data.config_json_written",
            elapsed_sec=round(time.perf_counter() - t_sub, 4),
            settings_size=_safe_getsize(settings_path),
            title_config_size=_safe_getsize(title_path),
            gallery_config_size=_safe_getsize(gallery_path),
            extra_text_config_size=_safe_getsize(extra_text_path),
            runtime_settings=_runtime_settings_log_stats(runtime_settings),
        )
    if pipeline_log:
        pipeline_log(
            "runtime_tree.story_data.done",
            elapsed_sec=round(time.perf_counter() - t_stage, 4),
            story_size=_safe_getsize(story_path),
            story_json_format="compact",
            settings_size=_safe_getsize(settings_path),
            endings_size=_safe_getsize(endings_path),
            title_config_size=_safe_getsize(title_path),
            gallery_config_size=_safe_getsize(gallery_path),
            extra_text_config_size=_safe_getsize(extra_text_path),
        )

    t_stage = time.perf_counter()
    _progress(progress, "Copying game assets")
    endings = (endings_override if endings_override is not None
               else getattr(state, "endings", []))
    asset_files = (
        set(asset_files_override)
        if asset_files_override is not None
        else _collect_asset_files(script, endings)
    )
    asset_files.update(_collect_title_asset_files(title_config))
    asset_files.update(_collect_gallery_asset_files(gallery_config))
    copy_files = (
        asset_files if bundle_original_images
        else _non_image_asset_files(asset_files)
    )
    if not copy_audio_assets:
        copy_files = {p for p in copy_files if not _is_audio_asset(p)}
    copied_assets = _copy_asset_files(copy_files, proj_base, app_dir)
    if pipeline_log:
        pipeline_log(
            "runtime_tree.game_assets.done",
            elapsed_sec=round(time.perf_counter() - t_stage, 4),
            requested_asset_count=len(copy_files),
            copied_asset_count=len(copied_assets),
        )
    runtime_report = _runtime_report_base(
        script=script,
        endings=endings,
        asset_files=asset_files,
        copied_assets=copied_assets,
        bundle_original_images=bundle_original_images,
        copy_audio_assets=copy_audio_assets,
    )
    t_stage = time.perf_counter()
    _progress(progress, "Prebuilding image cache")
    try:
        manifest = _prebuild_image_manifest_via_worker(
            script, endings, runtime_settings or {}, proj_base,
            app_dir, dst_cache_name="pvnm_cache",
            gallery_config=gallery_config,
            title_config=title_config,
            progress=progress)
        runtime_report["image_manifest"] = _image_manifest_report(manifest)
    except Exception as e:
        print(f"[export] prebuilt image manifest failed: {e}")
        runtime_report["image_manifest"] = {
            "ok": False,
            "error": str(e),
        }
        if not bundle_original_images:
            raise
        copied_cache = _copy_image_cache(
            proj_base, app_dir, asset_files, dst_cache_name="pvnm_cache")
        runtime_report["copied_cache_files"] = copied_cache
    if pipeline_log:
        pipeline_log(
            "runtime_tree.prebuild.done",
            elapsed_sec=round(time.perf_counter() - t_stage, 4),
            image_manifest=_compact_image_manifest_report(
                runtime_report.get("image_manifest", {})),
            cache_stats=_image_manifest_cache_quick_stats(
                os.path.join(app_dir, "pvnm_cache"),
                runtime_report.get("image_manifest", {})),
        )
    t_stage = time.perf_counter()
    _progress(progress, "Copying runtime assets")
    _copy_runtime_assets(app_dir)
    if pipeline_log:
        pipeline_log(
            "runtime_tree.runtime_assets.done",
            elapsed_sec=round(time.perf_counter() - t_stage, 4),
            assets_stats=_quick_path_stats(os.path.join(app_dir, "assets")),
        )

    t_stage = time.perf_counter()
    _progress(progress, "Copying player code")
    for rel in _COPY_FILES:
        src = os.path.join(_ROOT, rel)
        dst = os.path.join(app_dir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if os.path.exists(src):
            _copy_file_fast(src, dst)
        else:
            open(dst, "w").close()
    if pipeline_log:
        pipeline_log(
            "runtime_tree.player_code.done",
            elapsed_sec=round(time.perf_counter() - t_stage, 4),
            engine_stats=_quick_path_stats(os.path.join(app_dir, "engine")),
            ui_stats=_quick_path_stats(os.path.join(app_dir, "ui")),
        )

    t_stage = time.perf_counter()
    _progress(progress, "Writing player launcher")
    main_src = _MAIN_TEMPLATE.format(
        title=title.replace('"', '\\"'),
        storage_app_id=_storage_app_id(title).replace('"', '\\"'),
    )
    with open(os.path.join(app_dir, "main.py"), "w", encoding="utf-8") as f:
        f.write(main_src)

    readme = (
        "# Runtime requirements\n\n"
        "- pyxel 2.9 or later\n"
        "- pygame 2.6 or later (for 44.1kHz audio playback)\n\n"
        "Install with:\n"
        "    pip install -r requirements.txt\n\n"
        "If pygame is not installed, PVNM tries AVFoundation on macOS and "
        "then falls back to Pyxel PCM audio.\n"
        f"BDF fonts and the master palette are bundled in this {package_label}.\n"
        "Images may be prebuilt into image_manifest.json + pvnm_cache/*.npy "
        "instead of bundled as original image files.\n"
    )
    with open(os.path.join(app_dir, "README.md"), "w", encoding="utf-8") as f:
        f.write(readme)
    req_src = os.path.join(_ROOT, "requirements.txt")
    if os.path.exists(req_src):
        _copy_file_fast(req_src, os.path.join(app_dir, "requirements.txt"))
    _copy_export_license_notices(
        app_dir, pipeline_log=pipeline_log,
        event_prefix="runtime_tree.license_notices")
    if pipeline_log:
        pipeline_log(
            "runtime_tree.launcher.done",
            elapsed_sec=round(time.perf_counter() - t_stage, 4),
        )
    return runtime_report


def _copy_export_license_notices(
        dst_dir: str,
        pipeline_log=None,
        event_prefix: str = "license_notices") -> list[str]:
    """Copy PVNM runtime license notices into an exported artifact folder.

    Exported games are not automatically MIT-licensed just because they include
    PVNM runtime files. Use explicit PVNM-prefixed filenames so these notices
    are clearly scoped to the engine/runtime and bundled third-party code.
    """
    copied: list[str] = []
    os.makedirs(dst_dir, exist_ok=True)
    for src_name, dst_name in _EXPORT_LICENSE_FILES:
        src = os.path.join(_ROOT, src_name)
        if not os.path.isfile(src):
            continue
        dst = os.path.join(dst_dir, dst_name)
        _copy_file_fast(src, dst)
        copied.append(dst_name)
    readme_path = os.path.join(dst_dir, _EXPORT_LICENSE_README)
    _write_text_file(readme_path, _export_license_readme_text())
    copied.append(_EXPORT_LICENSE_README)
    if pipeline_log:
        pipeline_log(
            f"{event_prefix}.done",
            destination=os.path.abspath(dst_dir),
            files=copied,
        )
    return copied


