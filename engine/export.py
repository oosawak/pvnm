def _externalize_web_pyxapp(html_path: str, dst_dir: str, root_url: str,
                            runtime_report: dict | None = None) -> None:
    """Move app2html's embedded .pyxapp base64 into a same-origin asset file."""
    with open(html_path, "r", encoding="utf-8") as f:
        html = f.read()

    pattern = re.compile(
        r'launchPyxel\(\{\s*'
        r'command:\s*"play",\s*'
        r'name:\s*"(?P<name>[^"]+)",\s*'
        r'gamepad:\s*"(?P<gamepad>[^"]*)",\s*'
        r'base64:\s*"(?P<base64>[A-Za-z0-9+/=]+)"\s*,?\s*'
        r'\}\);',
        re.DOTALL,
    )
    match = pattern.search(html)
    if not match:
        if isinstance(runtime_report, dict):
            runtime_report["external_web_pyxapp"] = {
                "ok": False,
                "error": "launchPyxel embedded pyxapp block not found",
            }
        return

    original_name = match.group("name")
    app_name = os.path.basename(original_name) or "index.pyxapp"
    os.makedirs(dst_dir, exist_ok=True)
    dst_path = os.path.join(dst_dir, app_name)
    data = base64.b64decode(match.group("base64"))
    with open(dst_path, "wb") as f:
        f.write(data)

    root_json = json.dumps(root_url, ensure_ascii=False).replace("</", "<\\/")
    name_json = json.dumps(app_name, ensure_ascii=False).replace("</", "<\\/")
    # PVNM handles touch/click input itself and supports physical controllers
    # through the browser/Pyxel gamepad APIs. Pyxel's app2html "enabled"
    # flag adds an on-screen virtual gamepad on touch devices, which covers the
    # lower dialog area on Android, so keep that overlay disabled.
    gamepad_json = json.dumps("disabled", ensure_ascii=False).replace("</", "<\\/")
    replacement = (
        "if (window.PVNM_STARTUP) { "
        "window.PVNM_STARTUP.mark("
        '"pyxel.launch.call", '
        f"{{ root: {root_json}, name: {name_json} }}"
        "); "
        "}\n"
        "launchPyxel({ "
        'command: "play", '
        f"root: {root_json}, "
        f"name: {name_json}, "
        f"gamepad: {gamepad_json} "
        "});"
    )
    html = html[:match.start()] + replacement + html[match.end():]
    with open(html_path, "w", encoding="utf-8") as f:
        f.write(html)

    if isinstance(runtime_report, dict):
        runtime_report["external_web_pyxapp"] = {
            "ok": True,
            "path": f"{root_url.rstrip('/')}/{app_name}",
            "file": app_name,
            "size": len(data),
        }


