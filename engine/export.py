def _normalize_macos_app_output_path(output_path: str) -> tuple[str, str]:
    """Return (bundle_path, app_name) for a user-selected macOS app path.

    macOS save dialogs may treat an existing .app bundle as a directory. If the
    user confirms a path inside it, such as ".../Game.app/.app", collapse it
    back to ".../Game.app" so export overwrites the bundle itself.
    """
    raw = os.path.abspath(os.path.normpath(str(output_path or "")))
    parts = raw.split(os.sep)
    for i, part in enumerate(parts):
        if part.endswith(".app"):
            raw = os.sep.join(parts[:i + 1]) or os.sep
            break
    if not raw.endswith(".app"):
        raw += ".app"
    app_name = os.path.splitext(os.path.basename(raw))[0]
    if not app_name or app_name.startswith("."):
        app_name = "untitled"
        raw = os.path.join(os.path.dirname(raw), app_name + ".app")
    return raw, app_name


def _safe_windows_app_name(raw: str) -> str:
    safe = "".join(
        ch if ch.isalnum() or ch in ("-", "_", ".") else "_"
        for ch in str(raw or "")
    ).strip("._")
    return safe or "PVNMGame"


def _normalize_windows_exe_output_path(
        output_path: str,
        title: str = "My Visual Novel",
        make_zip: bool = True) -> tuple[str, str, str, str | None]:
    """Return (output_path, app_name, final_dir, zip_path)."""
    raw_value = str(output_path or "").strip()
    if not raw_value:
        raw_value = "PVNMGame-windows.zip" if make_zip else "PVNMGame"
    raw = os.path.abspath(os.path.normpath(raw_value))
    ext = os.path.splitext(raw)[1].lower()
    if ext == ".zip":
        out_path = raw
        stem = os.path.splitext(os.path.basename(raw))[0]
        for suffix in ("-windows", "_windows"):
            if stem.lower().endswith(suffix):
                stem = stem[:-len(suffix)]
                break
        app_name = _safe_windows_app_name(stem or title)
        final_dir = os.path.join(os.path.dirname(raw), app_name)
        zip_path = raw if make_zip else None
    elif ext == ".exe":
        app_name = _safe_windows_app_name(os.path.splitext(
            os.path.basename(raw))[0] or title)
        final_dir = os.path.join(os.path.dirname(raw), app_name)
        zip_path = (os.path.join(os.path.dirname(raw),
                                 f"{app_name}-windows.zip")
                    if make_zip else None)
        out_path = zip_path or raw
    else:
        app_name = _safe_windows_app_name(os.path.basename(raw) or title)
        final_dir = raw
        zip_path = (os.path.join(os.path.dirname(final_dir),
                                 f"{app_name}-windows.zip")
                    if make_zip else None)
        out_path = zip_path or final_dir
    return out_path, app_name, final_dir, zip_path


def _fit_icon_png(icon_src: str, size: int, dst_path: str) -> None:
    """Write a square PNG icon preserving the whole source image."""
    from PIL import Image

    with Image.open(icon_src) as src:
        img = src.convert("RGBA")
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    img.thumbnail((size, size), Image.Resampling.LANCZOS)
    x = (size - img.width) // 2
    y = (size - img.height) // 2
    canvas.alpha_composite(img, (x, y))
    os.makedirs(os.path.dirname(dst_path) or ".", exist_ok=True)
    canvas.save(dst_path)


def _make_macos_icns(icon_src: str, dst_icns: str) -> str | None:
    """Generate a macOS .icns file for PyInstaller, when Pillow/iconutil exist."""
    if sys.platform != "darwin":
        return None
    try:
        from PIL import Image  # noqa: F401
    except Exception as exc:
        print(f"[export] macOS icon skipped: Pillow unavailable ({exc})")
        return None

    iconset = os.path.splitext(dst_icns)[0] + ".iconset"
    try:
        if os.path.isdir(iconset):
            shutil.rmtree(iconset)
        os.makedirs(iconset, exist_ok=True)
        for name, size in (
            ("icon_16x16.png", 16),
            ("icon_16x16@2x.png", 32),
            ("icon_32x32.png", 32),
            ("icon_32x32@2x.png", 64),
            ("icon_128x128.png", 128),
            ("icon_128x128@2x.png", 256),
            ("icon_256x256.png", 256),
            ("icon_256x256@2x.png", 512),
            ("icon_512x512.png", 512),
            ("icon_512x512@2x.png", 1024),
        ):
            _fit_icon_png(icon_src, size, os.path.join(iconset, name))
        result = subprocess.run(
            ["iconutil", "-c", "icns", iconset, "-o", dst_icns],
            capture_output=True,
            text=True,
            timeout=30,
        )
        if result.returncode != 0 or not os.path.exists(dst_icns):
            msg = (result.stderr or result.stdout or "").strip()
            print(f"[export] macOS icon skipped: iconutil failed {msg}")
            return None
        return dst_icns
    except Exception as exc:
        print(f"[export] macOS icon skipped: {exc}")
        return None


def _make_windows_ico(icon_src: str, dst_ico: str) -> str | None:
    """Generate a Windows .ico file for PyInstaller."""
    try:
        from PIL import Image
    except Exception as exc:
        print(f"[export] Windows icon skipped: Pillow unavailable ({exc})")
        return None

    try:
        with Image.open(icon_src) as src:
            img = src.convert("RGBA")
        canvas = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
        resampling = getattr(Image, "Resampling", Image)
        lanczos = getattr(resampling, "LANCZOS", getattr(Image, "LANCZOS", 1))
        img.thumbnail((1024, 1024), lanczos)
        x = (1024 - img.width) // 2
        y = (1024 - img.height) // 2
        canvas.alpha_composite(img, (x, y))
        os.makedirs(os.path.dirname(dst_ico) or ".", exist_ok=True)
        canvas.save(
            dst_ico,
            format="ICO",
            sizes=[
                (16, 16),
                (24, 24),
                (32, 32),
                (48, 48),
                (64, 64),
                (128, 128),
                (256, 256),
            ],
        )
        return dst_ico
    except Exception as exc:
        print(f"[export] Windows icon skipped: {exc}")
        return None


