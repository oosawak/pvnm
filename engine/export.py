def _is_image_asset(path: str) -> bool:
    return os.path.splitext(str(path or ""))[1].lower() in _IMAGE_EXTS


def _non_image_asset_files(asset_files: set[str]) -> set[str]:
    """Return assets that must remain real files in image-lite exports."""
    return {p for p in asset_files if not _is_image_asset(p)}


def _copy_asset_files(asset_files: set[str], src_base: str, dst_dir: str) -> list[str]:
    """参照アセットを dst_dir に相対パスを保ったままコピーする。"""
    copied: list[str] = []
    for rel_path in asset_files:
        src_raw = (os.path.join(src_base, rel_path)
                   if not os.path.isabs(rel_path) else rel_path)
        src = _existing_path_variant(src_raw)
        if not src:
            continue
        dst = os.path.join(dst_dir, rel_path)
        os.makedirs(os.path.dirname(dst) or dst_dir, exist_ok=True)
        _copy_file_fast(src, dst)
        copied.append(str(rel_path))
    return copied


def _existing_path_variant(path: str) -> str:
    """Return an existing NFC/NFD variant for cross-platform asset paths."""
    if not path:
        return ""
    path = str(path)
    if os.path.exists(path):
        return path
    for form in ("NFC", "NFD"):
        try:
            candidate = unicodedata.normalize(form, path)
        except Exception:
            continue
        if candidate != path and os.path.exists(candidate):
            return candidate
    return ""


