def _write_sha256_sidecar(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(chunk)
    out_path = path + ".sha256"
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(f"{digest.hexdigest()}  {os.path.basename(path)}\n")
    return out_path


def _script_quick_counts(script: dict) -> dict:
    scenes = script.get("scenes", []) if isinstance(script, dict) else []
    step_count = 0
    choice_count = 0
    bg_count = 0
    char_count = 0
    for scene in scenes:
        if not isinstance(scene, dict):
            continue
        steps = scene.get("steps", []) or []
        step_count += len(steps)
        for step in steps:
            if isinstance(step, dict) and step.get("op") == "choice":
                choice_count += len(step.get("options", []) or [])
        if scene.get("bg"):
            bg_count += 1
        for key in ("char_l", "char_c", "char_r"):
            value = scene.get(key)
            if isinstance(value, dict) and value.get("file"):
                char_count += 1
    return {
        "scene_count": len(scenes),
        "step_count": step_count,
        "choice_count": choice_count,
        "bg_ref_count": bg_count,
        "char_ref_count": char_count,
    }


def _remove_path(path: str) -> None:
    if os.path.isdir(path) and not os.path.islink(path):
        shutil.rmtree(path)
    elif os.path.exists(path):
        os.remove(path)


def _move_path_fast(src: str, dst: str) -> str:
    """Move a file/dir with rename first; fall back to shutil.move."""
    os.makedirs(os.path.dirname(dst) or ".", exist_ok=True)
    if os.path.exists(dst):
        _remove_path(dst)
    try:
        os.replace(src, dst)
        return "rename"
    except OSError:
        shutil.move(src, dst)
        return "move"


def _zip_dir(src_dir: str, zip_path: str) -> None:
    """Zip a directory while preserving the top-level folder name."""
    if os.path.exists(zip_path):
        os.remove(zip_path)
    os.makedirs(os.path.dirname(zip_path) or ".", exist_ok=True)
    parent = os.path.dirname(src_dir)
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for root, _dirs, files in os.walk(src_dir):
            for name in sorted(files):
                path = os.path.join(root, name)
                zf.write(path, os.path.relpath(path, parent))


def _clone_file_fast(src: str, dst: str) -> bool:
    """Create a copy-on-write clone on APFS/macOS when available."""
    if sys.platform != "darwin":
        return False
    try:
        import ctypes
        import ctypes.util
        libc_path = ctypes.util.find_library("c") or "/usr/lib/libc.dylib"
        libc = ctypes.CDLL(libc_path, use_errno=True)
        clonefile = libc.clonefile
        clonefile.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint32]
        clonefile.restype = ctypes.c_int
        return clonefile(os.fsencode(src), os.fsencode(dst), 0) == 0
    except Exception:
        return False


def _copy_file_fast(src: str, dst: str) -> str:
    """Use clone/hardlink for temporary package inputs; fall back to copy2."""
    os.makedirs(os.path.dirname(dst) or ".", exist_ok=True)
    if os.path.exists(dst):
        os.remove(dst)
    if _clone_file_fast(src, dst):
        return "clone"
    try:
        os.link(src, dst)
        return "hardlink"
    except OSError:
        shutil.copy2(src, dst)
        return "copy"


