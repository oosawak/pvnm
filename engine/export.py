def _run_full_export_worker(
        kind: str,
        project_path: str,
        output_path: str,
        settings: dict | None = None,
        title: str = "My Visual Novel",
        progress=None,
        asset_dir_name: str | None = None,
        bundle_original_images: bool = False,
        embed_audio: bool = False,
        app_id: str | None = None,
        variant: str = "release",
        project_dir: str | None = None,
        make_zip: bool = True) -> tuple[bool, str]:
    """Run a full export outside the live Pyxel GUI process."""
    out_dir = os.path.abspath(os.path.dirname(output_path) or ".")
    os.makedirs(out_dir, exist_ok=True)
    worker_label = {
        "pyxapp": ".pyxapp export worker",
        "pyxapp_external": "portable export worker",
        "capacitor_project": "Capacitor export worker",
        "android_apk": f"Android {('release' if variant == 'release' else 'debug')} APK export worker",
        "macos_app": "macOS app export worker",
        "windows_exe": "Windows EXE export worker",
    }.get(kind, "export worker")
    payload = {
        "kind": kind,
        "project_path": os.path.abspath(project_path),
        "output_path": os.path.abspath(output_path),
        "settings": settings or {},
        "title": title,
        "asset_dir_name": asset_dir_name,
        "bundle_original_images": bool(bundle_original_images),
        "embed_audio": bool(embed_audio),
        "app_id": app_id,
        "variant": "release" if variant == "release" else "debug",
        "project_dir": os.path.abspath(project_dir) if project_dir else None,
        "make_zip": bool(make_zip),
    }
    _progress(progress, f"Starting {worker_label}")
    with tempfile.TemporaryDirectory(prefix="pvnm_export_worker_") as tmp:
        input_path = os.path.join(tmp, "export_worker_input.json")
        result_path = os.path.join(tmp, "export_worker_result.json")
        payload["result_path"] = result_path
        with open(input_path, "w", encoding="utf-8") as f:
            json.dump(payload, f, ensure_ascii=False)

        cmd = [
            sys.executable,
            "-B",
            "-m",
            "engine.export_worker",
            input_path,
        ]
        env = os.environ.copy()
        env["PYTHONPATH"] = (
            _ROOT if not env.get("PYTHONPATH")
            else _ROOT + os.pathsep + env["PYTHONPATH"]
        )
        env["PVNM_EXPORT_INLINE_FULL"] = "1"
        lines: list[str] = []
        try:
            proc = subprocess.Popen(
                cmd,
                cwd=_ROOT,
                env=env,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                bufsize=1,
            )
        except Exception as exc:
            return False, f"Export worker launch failed: {exc}"

        assert proc.stdout is not None
        for line in proc.stdout:
            text = line.rstrip("\n")
            if text.startswith("PVNM_PROGRESS\t"):
                _progress(progress, text.split("\t", 1)[1])
                continue
            if text:
                lines.append(text)
                print(text)
                if len(lines) > 120:
                    del lines[:len(lines) - 120]
        rc = proc.wait()

        result = {}
        if os.path.exists(result_path):
            try:
                with open(result_path, encoding="utf-8") as f:
                    result = json.load(f)
            except Exception:
                result = {}
        if isinstance(result, dict) and result.get("ok") is True:
            return True, str(result.get("message") or output_path)
        message = ""
        if isinstance(result, dict):
            message = str(result.get("message") or "")
        if not message:
            tail = "\n".join(lines[-30:])
            message = (
                "Export worker failed"
                + (f":\n{tail}" if tail else f" (exit {rc})")
            )
        return False, message


def _make_export_pipeline_logger(kind: str, out_dir: str, app_name: str):
    """Return a small JSONL logger for export stages outside image prebuild."""
    run_id = time.strftime("%Y%m%d_%H%M%S") + f"_{os.getpid()}"
    log_dir = os.path.join(os.path.abspath(out_dir or _ROOT),
                           ".pvnm_export_logs")
    try:
        os.environ["PVNM_EXPORT_LOG_DIR"] = log_dir
    except Exception:
        pass
    paths: list[str] = []
    try:
        os.makedirs(log_dir, exist_ok=True)
        paths.append(os.path.join(log_dir, f"export_pipeline_{run_id}.jsonl"))
        paths.append(os.path.join(log_dir, "export_pipeline.latest.jsonl"))
    except Exception:
        paths = []

    base = {
        "run_id": run_id,
        "kind": kind,
        "app_name": app_name,
        "out_dir": os.path.abspath(out_dir),
    }
    start = time.perf_counter()

    def log(event: str, **fields) -> None:
        if not paths:
            return
        stage_elapsed = fields.pop("elapsed_sec", None)
        record = dict(base)
        record.update({
            "event": event,
            "elapsed_sec": round(time.perf_counter() - start, 4),
            "time": time.strftime("%Y-%m-%d %H:%M:%S"),
        })
        if stage_elapsed is not None:
            record["stage_elapsed_sec"] = stage_elapsed
        record.update(fields)
        line = json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n"
        for path in paths:
            try:
                mode = "w" if path.endswith(".latest.jsonl") and event == "start" else "a"
                with open(path, mode, encoding="utf-8") as f:
                    f.write(line)
            except Exception:
                pass

    return log


def _prebuild_image_manifest_via_worker(
        script: dict, endings: list | None,
        settings: dict, src_base: str, dst_dir: str,
        dst_cache_name: str = "pvnm_cache",
        gallery_config: dict | None = None,
        title_config: dict | None = None,
        progress=None) -> dict:
    """Run image prebuild in a separate Python process.

    Pillow/NumPy image work is dramatically slower when it runs inside the
    live Pyxel editor process on some macOS environments. The standalone worker
    uses the same implementation but avoids UI-loop contention, then writes the
    normal image_manifest.json and diagnostics into ``dst_dir``.
    """
    if os.environ.get("PVNM_EXPORT_INLINE_PREBUILD") == "1":
        return _prebuild_image_manifest(
            script, endings, settings, src_base, dst_dir,
            dst_cache_name=dst_cache_name,
            gallery_config=gallery_config,
            title_config=title_config,
            progress=progress)

    os.makedirs(dst_dir, exist_ok=True)
    input_path = os.path.join(dst_dir, "image_prebuild_input.json")
    result_path = os.path.join(dst_dir, "image_prebuild_worker_result.json")
    payload = {
        "script": script or {},
        "endings": endings or [],
        "settings": settings or {},
        "src_base": src_base,
        "dst_dir": dst_dir,
        "dst_cache_name": dst_cache_name,
        "gallery_config": gallery_config or {},
        "title_config": title_config or {},
    }
    with open(input_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False)

    cmd = [
        sys.executable,
        "-B",
        "-m",
        "engine.export_prebuild_worker",
        input_path,
        result_path,
    ]
    env = os.environ.copy()
    env["PYTHONPATH"] = (
        _ROOT if not env.get("PYTHONPATH")
        else _ROOT + os.pathsep + env["PYTHONPATH"]
    )
    _progress(progress, "Prebuilding image cache in worker")
    lines: list[str] = []
    try:
        proc = subprocess.Popen(
            cmd,
            cwd=_ROOT,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )
    except Exception:
        try:
            os.remove(input_path)
        except OSError:
            pass
        raise

    assert proc.stdout is not None
    for line in proc.stdout:
        text = line.rstrip("\n")
        if text.startswith("PVNM_PROGRESS\t"):
            _progress(progress, text.split("\t", 1)[1])
            continue
        if text:
            lines.append(text)
            print(text)
            if len(lines) > 80:
                del lines[:len(lines) - 80]
    rc = proc.wait()
    try:
        os.remove(input_path)
    except OSError:
        pass
    if rc != 0:
        tail = "\n".join(lines[-30:])
        raise RuntimeError(
            "image prebuild worker failed"
            + (f":\n{tail}" if tail else "")
        )
    if os.path.exists(result_path):
        try:
            with open(result_path, encoding="utf-8") as f:
                result = json.load(f)
            elapsed = result.get("elapsed_sec")
            generated = result.get("generated")
            unique = result.get("unique")
            if elapsed is not None:
                _progress(
                    progress,
                    "Prebuilding image cache complete: "
                    f"{unique} unique / {generated} generated / "
                    f"{float(elapsed):.1f}s",
                )
        except Exception:
            pass
        try:
            os.remove(result_path)
        except OSError:
            pass
    manifest_path = os.path.join(dst_dir, "image_manifest.json")
    with open(manifest_path, encoding="utf-8") as f:
        manifest = json.load(f)
    return manifest


def _write_runtime_json(state, settings: dict,
                        settings_path: str, endings_path: str):
    """Runtime settings needed by the exported player."""
    runtime_settings = {}
    try:
        import ui.colors as _colors
        runtime_settings["dialog_role_indices"] = {
            role: _colors.current_index(role)
            for role in _colors.role_names()
        }
    except Exception:
        pass
    if isinstance(settings, dict):
        role = settings.get("dialog_role_indices")
        if isinstance(role, dict):
            runtime_settings["dialog_role_indices"] = role
        speakers = settings.get("speaker_colors")
        if isinstance(speakers, dict):
            runtime_settings["speaker_colors"] = speakers
        dialog_size = settings.get("dialog_font_size")
        if isinstance(dialog_size, int):
            runtime_settings["dialog_font_size"] = dialog_size
    runtime_settings.setdefault("speaker_colors", {
        "narration_text_color": None,
        "speakers": {},
    })
    # EditorState keeps speaker colors in app settings, not on state. Main passes
    # them through settings.json in normal editor runs, so preserve absent data as
    # an empty config for compatibility.
    with open(settings_path, "w", encoding="utf-8") as f:
        json.dump(runtime_settings, f, ensure_ascii=False, indent=2)
    with open(endings_path, "w", encoding="utf-8") as f:
        json.dump(getattr(state, "endings", []) or [],
                  f, ensure_ascii=False, indent=2)
    return runtime_settings


