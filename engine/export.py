def export_pyxapp(state, output_path: str,
                  settings: dict | None = None,
                  title: str = "My Visual Novel",
                  progress=None,
                  bundle_original_images: bool = False) -> tuple[bool, str]:
    """
    EditorState を .pyxapp ファイルとしてエクスポートする。

    Parameters
    ----------
    state       : EditorState
    output_path : 出力先パス（例: "./my_game.pyxapp"）
    title       : ゲームウィンドウタイトル

    Returns
    -------
    (True, 出力ファイルパス) または (False, エラーメッセージ)
    """
    if os.environ.get("PVNM_EXPORT_INLINE_FULL") == "1":
        return _export_pyxapp_inline(
            state, output_path, settings=settings, title=title,
            progress=progress,
            bundle_original_images=bundle_original_images)
    project_path = str(getattr(state, "file_path", "") or "")
    if not project_path or not os.path.isfile(project_path):
        return _export_pyxapp_inline(
            state, output_path, settings=settings, title=title,
            progress=progress,
            bundle_original_images=bundle_original_images)
    return _export_pyxapp_via_worker(
        project_path, output_path, settings=settings, title=title,
        progress=progress,
        bundle_original_images=bundle_original_images)


def _export_pyxapp_inline(state, output_path: str,
                          settings: dict | None = None,
                          title: str = "My Visual Novel",
                          progress=None,
                          bundle_original_images: bool = False
                          ) -> tuple[bool, str]:
    """Build a single .pyxapp in the current process."""
    out_dir  = os.path.abspath(os.path.dirname(output_path) or ".")
    app_name = os.path.splitext(os.path.basename(output_path))[0]

    os.makedirs(out_dir, exist_ok=True)
    _progress(progress, "Preparing export workspace")
    pipeline_log = _make_export_pipeline_logger("pyxapp", out_dir, app_name)
    pipeline_log(
        "start",
        output_path=os.path.abspath(output_path),
        bundle_original_images=bool(bundle_original_images),
    )
    export_started = time.perf_counter()

    # プロジェクトの画像ファイルのベースディレクトリ
    proj_base = (os.path.dirname(os.path.abspath(state.file_path))
                 if state.file_path else out_dir)

    with tempfile.TemporaryDirectory() as tmp:
        app_dir = os.path.join(tmp, app_name)
        os.makedirs(app_dir)
        t0 = time.perf_counter()
        pipeline_log("runtime_tree.start", app_dir=app_dir)
        _write_runtime_tree(
            state, app_dir, proj_base, settings or {}, title,
            package_label=".pyxapp", progress=progress,
            bundle_original_images=bundle_original_images,
            pipeline_log=pipeline_log)
        pipeline_log(
            "runtime_tree.done",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            app_dir_stats=_quick_path_stats(app_dir),
        )

        # ── pyxel package コマンドを実行 ──
        _progress(progress, "Packaging .pyxapp")
        t0 = time.perf_counter()
        pipeline_log("package.start", cwd=out_dir)
        try:
            result = subprocess.run(
                [sys.executable, "-m", "pyxel", "package", app_dir,
                 os.path.join(app_dir, "main.py")],
                capture_output=True, text=True, timeout=60, cwd=out_dir,
            )
        except subprocess.TimeoutExpired:
            pipeline_log(
                "package.timeout",
                elapsed_sec=round(time.perf_counter() - t0, 4),
            )
            return False, "Export timed out (>60s)"
        except Exception as e:
            pipeline_log(
                "package.error",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                error=str(e),
            )
            return False, str(e)
        pipeline_log(
            "package.done",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            returncode=result.returncode,
            stdout_len=len(result.stdout or ""),
            stderr_len=len(result.stderr or ""),
        )

        if result.returncode != 0:
            err = (result.stderr or result.stdout).strip()
            return False, err[:120] if err else "pyxel package failed"

        out_file = os.path.join(out_dir, f"{app_name}.pyxapp")
        if not os.path.exists(out_file):
            return False, ".pyxapp file not found after package"

        _progress(progress, "Export complete")
        pipeline_log(
            "complete",
            elapsed_sec=round(time.perf_counter() - export_started, 4),
            output_pyxapp=out_file,
            output_pyxapp_size=os.path.getsize(out_file),
        )
        return True, out_file


