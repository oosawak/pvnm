def _export_android_apk_inline(state, output_path: str,
                               variant: str = "release",
                               project_dir: str | None = None,
                               settings: dict | None = None,
                               title: str = "My Visual Novel",
                               progress=None) -> tuple[bool, str]:
    """Export/update a Capacitor project, build an APK, and copy it out."""
    variant = "release" if variant == "release" else "debug"
    output_path = os.path.abspath(output_path)
    out_dir = os.path.dirname(output_path) or "."
    app_name = title or os.path.splitext(os.path.basename(output_path))[0]
    pipeline_log = _make_export_pipeline_logger(
        f"android_apk_{variant}", out_dir, app_name)
    export_started = time.perf_counter()
    if project_dir is None:
        base = os.path.splitext(output_path)[0]
        for suffix in ("-debug", "-release", "_debug", "_release"):
            if base.lower().endswith(suffix):
                base = base[:-len(suffix)] or os.path.splitext(output_path)[0]
                break
        project_dir = base + "_android"
    project_dir = os.path.abspath(project_dir)
    pipeline_log(
        "android_apk.start",
        variant=variant,
        output_path=output_path,
        project_dir=project_dir,
        source_file=getattr(state, "file_path", "") or "",
    )

    _progress(progress, "Preparing Android project")
    t0 = time.perf_counter()
    pipeline_log("android_apk.capacitor_project.start")
    ok, msg = _export_capacitor_project_inline(
        state,
        project_dir,
        settings=settings,
        title=title,
        progress=progress,
        bundle_original_images=False,
        embed_audio=False,
        pipeline_log=pipeline_log,
    )
    if not ok:
        pipeline_log(
            "android_apk.capacitor_project.error",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            message=msg,
        )
        return False, msg
    pipeline_log(
        "android_apk.capacitor_project.done",
        elapsed_sec=round(time.perf_counter() - t0, 4),
    )

    build_mode = "build-release" if variant == "release" else "build-debug"
    script = os.path.join(project_dir, "build_android.sh")
    if not os.path.exists(script):
        pipeline_log("android_apk.build_script.missing", script=script)
        return False, f"build_android.sh not found: {script}"

    _progress(progress, f"Building Android {variant} APK")
    last_lines: list[str] = []
    t0 = time.perf_counter()
    pipeline_log(
        "android_apk.gradle_build.start",
        build_mode=build_mode,
        script=script,
    )
    try:
        proc = subprocess.Popen(
            ["sh", script, build_mode],
            cwd=project_dir,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )
        assert proc.stdout is not None
        for raw in proc.stdout:
            line = raw.strip()
            if not line:
                continue
            last_lines.append(line)
            del last_lines[:-8]
            _progress(progress, line[-120:])
        code = proc.wait()
    except FileNotFoundError as exc:
        pipeline_log(
            "android_apk.gradle_build.error",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            error=str(exc),
        )
        return False, f"Android build command not found: {exc}"
    except Exception as exc:
        pipeline_log(
            "android_apk.gradle_build.error",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            error=str(exc),
        )
        return False, f"Android build failed: {exc}"
    pipeline_log(
        "android_apk.gradle_build.done",
        elapsed_sec=round(time.perf_counter() - t0, 4),
        returncode=code,
        last_lines=last_lines[-8:],
    )

    if code != 0:
        tail = " / ".join(last_lines[-4:]) if last_lines else f"exit code {code}"
        return False, f"Android {variant} APK build failed: {tail[:300]}"

    apk_rel = ("android/app/build/outputs/apk/release/app-release.apk"
               if variant == "release"
               else "android/app/build/outputs/apk/debug/app-debug.apk")
    built_apk = os.path.join(project_dir, apk_rel)
    if not os.path.exists(built_apk):
        pipeline_log("android_apk.built_apk.missing", built_apk=built_apk)
        return False, f"Built APK not found: {built_apk}"

    try:
        if out_dir:
            os.makedirs(out_dir, exist_ok=True)
        t0 = time.perf_counter()
        pipeline_log(
            "android_apk.final_copy.start",
            built_apk=built_apk,
            built_apk_size=_safe_getsize(built_apk),
            output_path=output_path,
        )
        copy_mode = _copy_file_fast(built_apk, output_path)
        sha256_path = ""
        if variant == "release":
            sha256_path = _write_sha256_sidecar(output_path)
        _copy_export_license_notices(
            out_dir, pipeline_log=pipeline_log,
            event_prefix="android_apk.license_notices")
        pipeline_log(
            "android_apk.final_copy.done",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            mode=copy_mode,
            output_apk_size=_safe_getsize(output_path),
            sha256_path=sha256_path,
            sha256_size=_safe_getsize(sha256_path) if sha256_path else 0,
        )
    except Exception as exc:
        pipeline_log("android_apk.final_copy.error", error=str(exc))
        return False, f"APK copy failed: {exc}"

    _progress(progress, "Android APK export complete")
    pipeline_log(
        "android_apk.complete",
        elapsed_sec=round(time.perf_counter() - export_started, 4),
        output_path=output_path,
        output_apk_size=_safe_getsize(output_path),
        output_sha256=output_path + ".sha256" if variant == "release" else "",
    )
    return True, output_path


