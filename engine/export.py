def _export_pyxapp_external_assets_inline(
        state, output_path: str,
        settings: dict | None = None,
        title: str = "My Visual Novel",
        progress=None,
        asset_dir_name: str | None = None) -> tuple[bool, str]:
    """Export a small .pyxapp plus a sibling external asset folder.

    This is intended for Linux handhelds where ``pyxel play`` extracts the
    whole .pyxapp into /tmp. Images are served from prebuilt npy cache files and
    audio remains as normal files beside the .pyxapp.
    """
    out_dir = os.path.abspath(os.path.dirname(output_path) or ".")
    app_name = os.path.splitext(os.path.basename(output_path))[0]
    if not app_name or app_name.startswith("."):
        app_name = "untitled"
        output_path = os.path.join(out_dir, app_name + ".pyxapp")
    asset_dir_name = asset_dir_name or f"{app_name}_assets"
    final_asset_dir = os.path.join(out_dir, asset_dir_name)

    os.makedirs(out_dir, exist_ok=True)
    _progress(progress, "Preparing Linux portable export")
    proj_base = (os.path.dirname(os.path.abspath(state.file_path))
                 if state.file_path else out_dir)
    script = from_editor_state(state)
    endings = getattr(state, "endings", []) or []
    asset_files = _collect_asset_files(script, endings)
    title_config = _normalize_title_config(getattr(state, "title_config", {}))
    gallery_config = normalize_gallery_config(
        getattr(state, "gallery_config", {}))
    asset_files.update(_collect_title_asset_files(title_config))
    asset_files.update(_collect_gallery_asset_files(gallery_config))
    pipeline_log = _make_export_pipeline_logger(
        "pyxapp_external", out_dir, app_name)
    pipeline_log(
        "start",
        output_path=os.path.abspath(output_path),
        final_asset_dir=final_asset_dir,
        asset_file_count=len(asset_files),
    )
    export_started = time.perf_counter()

    with tempfile.TemporaryDirectory() as tmp:
        app_dir = os.path.join(tmp, app_name)
        tmp_asset_dir = os.path.join(tmp, asset_dir_name)
        os.makedirs(app_dir)
        t0 = time.perf_counter()
        pipeline_log("runtime_tree.start", app_dir=app_dir)
        runtime_report = _write_runtime_tree(
            state, app_dir, proj_base, settings or {}, title,
            package_label="Linux portable .pyxapp", progress=progress,
            bundle_original_images=False,
            copy_audio_assets=False,
            pipeline_log=pipeline_log,
            script_override=script,
            endings_override=endings,
            asset_files_override=asset_files)
        pipeline_log(
            "runtime_tree.done",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            app_dir_stats=_quick_path_stats(app_dir),
        )

        marker = {
            "version": 1,
            "kind": "pvnm-external-assets",
            "app_name": app_name,
            "asset_dir_name": asset_dir_name,
            "cache_dir": "pvnm_cache",
            "required": True,
        }
        with open(os.path.join(app_dir, "external_assets.json"),
                  "w", encoding="utf-8") as f:
            json.dump(marker, f, ensure_ascii=False, indent=2)

        _progress(progress, "Writing external assets")
        t0 = time.perf_counter()
        pipeline_log("external_assets.start", tmp_asset_dir=tmp_asset_dir)
        external_report = _write_pyxapp_external_asset_dir(
            app_dir, tmp_asset_dir, asset_files, proj_base,
            app_name, asset_dir_name, runtime_report,
            pipeline_log=pipeline_log)
        _copy_export_license_notices(
            tmp_asset_dir, pipeline_log=pipeline_log,
            event_prefix="external_assets.license_notices")
        pipeline_log(
            "external_assets.done",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            tmp_asset_dir_stats=_external_asset_quick_stats(
                tmp_asset_dir, external_report),
            image_cache_file_count=external_report.get("image_cache_file_count"),
            audio_asset_count=external_report.get("audio_asset_count"),
            missing_audio_count=len(external_report.get("missing_audio_assets") or []),
        )

        _progress(progress, "Packaging portable .pyxapp")
        t0 = time.perf_counter()
        pipeline_log("package.start", cwd=out_dir)
        try:
            result = subprocess.run(
                [sys.executable, "-m", "pyxel", "package", app_dir,
                 os.path.join(app_dir, "main.py")],
                capture_output=True, text=True, timeout=120, cwd=out_dir,
            )
        except subprocess.TimeoutExpired:
            pipeline_log(
                "package.timeout",
                elapsed_sec=round(time.perf_counter() - t0, 4),
            )
            return False, "Portable .pyxapp export timed out (>120s)"
        except Exception as e:
            pipeline_log(
                "package.error",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                error=str(e),
            )
            return False, str(e)
        pipeline_log(
            "package.done",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            returncode=result.returncode,
            stdout_len=len(result.stdout or ""),
            stderr_len=len(result.stderr or ""),
        )

        if result.returncode != 0:
            err = (result.stderr or result.stdout).strip()
            return False, err[:160] if err else "pyxel package failed"

        out_file = os.path.join(out_dir, f"{app_name}.pyxapp")
        if not os.path.exists(out_file):
            return False, ".pyxapp file not found after package"

        try:
            _progress(progress, "Copying external assets to destination")
            t0 = time.perf_counter()
            pipeline_log(
                "final_asset_copy.start",
                source=tmp_asset_dir,
                destination=final_asset_dir,
                source_stats=_external_asset_quick_stats(
                    tmp_asset_dir, external_report),
                output_pyxapp_size=os.path.getsize(out_file),
            )
            if os.path.exists(final_asset_dir):
                t_rm = time.perf_counter()
                pipeline_log("final_asset_copy.remove_existing.start")
                shutil.rmtree(final_asset_dir)
                pipeline_log(
                    "final_asset_copy.remove_existing.done",
                    elapsed_sec=round(time.perf_counter() - t_rm, 4),
                )
            move_mode = _move_path_fast(tmp_asset_dir, final_asset_dir)
            pipeline_log(
                "final_asset_copy.done",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                mode=move_mode,
                destination_stats=_external_asset_quick_stats(
                    final_asset_dir, external_report),
            )
        except Exception as e:
            pipeline_log("final_asset_copy.error", error=str(e))
            return False, f"Asset folder copy failed: {e}"

        _progress(progress, "Export complete")
        pipeline_log(
            "complete",
            elapsed_sec=round(time.perf_counter() - export_started, 4),
            output_pyxapp=out_file,
            output_pyxapp_size=os.path.getsize(out_file),
        )
        if external_report.get("missing_audio_assets"):
            print("[export] missing external audio assets:",
                  external_report["missing_audio_assets"])
        return True, out_file


