def _copy_pyxel_web_runtime(dst_root: str) -> None:
    src_root = os.path.join(_ROOT, _WEB_RUNTIME_DIR)
    missing = [
        rel for rel in _WEB_RUNTIME_REQUIRED_FILES
        if not os.path.exists(os.path.join(src_root, *rel.split("/")))
    ]
    if missing:
        raise RuntimeError(
            "Pyxel Web runtime files are missing: " + ", ".join(missing))

    for dirname in ("pyxel", "pyodide"):
        src = os.path.join(src_root, dirname)
        dst = os.path.join(dst_root, dirname)
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        elif os.path.exists(dst):
            os.remove(dst)
        shutil.copytree(src, dst)


def _npm_package_name(name: str) -> str:
    slug = re.sub(r"[^a-z0-9._-]+", "-", str(name).lower()).strip("._-")
    slug = re.sub(r"-{2,}", "-", slug)
    if not slug:
        slug = "pvnm-game"
    if slug[0] in ".-" or slug[0].isdigit():
        slug = "pvnm-" + slug.lstrip(".-")
    return slug[:80].rstrip(".-") or "pvnm-game"


