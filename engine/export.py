def _pyinstaller_data_args(app_dir: str) -> list[str]:
    """Return --add-data args for runtime data, excluding Python modules.

    The generated engine/ui Python packages are added through --paths so
    PyInstaller can analyze them as code. They are also copied as data because
    Pyxel's desktop init path expects physical project directories to exist in
    the runtime working directory. Avoid adding the whole runtime tree as one
    data item because that can corrupt macOS bundle symlink layout for
    Python.framework.
    """
    args: list[str] = []
    sep = os.pathsep
    skip_names = {"main.py", "__pycache__"}
    for name in sorted(os.listdir(app_dir)):
        if name in skip_names:
            continue
        src = os.path.join(app_dir, name)
        if not os.path.exists(src):
            continue
        dest = name if os.path.isdir(src) else "."
        args.extend(["--add-data", f"{src}{sep}{dest}"])
    return args


