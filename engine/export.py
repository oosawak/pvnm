def export_web_html(state, output_path: str,
                    settings: dict | None = None,
                    title: str = "My Visual Novel",
                    progress=None,
                    bundle_original_images: bool = False,
                    embed_audio: bool = False,
                    local_pyxel_runtime: bool = True,
                    asset_dir_name: str | None = None,
                    storage_namespace: str | None = None,
                    report_out: dict | None = None,
                    pipeline_log=None) -> tuple[bool, str]:
    """Export a Pyxel Web HTML with PVNM WebAudio bridge.

    This is the first Web/Android route: build the normal runtime tree, package
    it as .pyxapp, convert it with ``pyxel app2html``, then inject a JavaScript
    audio bridge. By default, referenced audio assets are copied beside the HTML
    into ``<name>_assets/audio/`` for Capacitor-friendly packaging. By
    default, the Pyxel/Pyodide Web runtime is also copied beside the HTML and
    the CDN script reference is replaced with ``pyxel/pyxel.js``. Set
    ``embed_audio=True`` for a single-file test HTML with data-URL audio.
    """
    out_path = _normalize_web_html_output_path(output_path)
    out_dir = os.path.abspath(os.path.dirname(out_path) or ".")
    app_name = os.path.splitext(os.path.basename(out_path))[0]
    if not app_name or app_name.startswith("."):
        app_name = "untitled"
        out_path = os.path.join(out_dir, app_name + ".html")

    os.makedirs(out_dir, exist_ok=True)
    _progress(progress, "Preparing Web HTML export")
    if pipeline_log:
        pipeline_log(
            "web_html.start",
            output_path=os.path.abspath(out_path),
            asset_dir_name=asset_dir_name or _web_asset_dir_name(app_name),
            bundle_original_images=bool(bundle_original_images),
            embed_audio=bool(embed_audio),
            local_pyxel_runtime=bool(local_pyxel_runtime),
        )
    proj_base = (os.path.dirname(os.path.abspath(state.file_path))
                 if state.file_path else out_dir)
    script = from_editor_state(state)
    endings = getattr(state, "endings", []) or []
    asset_files = _collect_asset_files(script, endings)
    title_config = _normalize_title_config(getattr(state, "title_config", {}))
    gallery_config = normalize_gallery_config(getattr(state, "gallery_config", {}))
    asset_files.update(_collect_title_asset_files(title_config))
    asset_files.update(_collect_gallery_asset_files(gallery_config))
    asset_dir_name = asset_dir_name or _web_asset_dir_name(app_name)

    with tempfile.TemporaryDirectory() as tmp:
        app_dir = os.path.join(tmp, app_name)
        tmp_web_assets_dir = os.path.join(tmp, asset_dir_name)
        os.makedirs(app_dir)
        t0 = time.perf_counter()
        if pipeline_log:
            pipeline_log("web_html.runtime_tree.start", app_dir=app_dir)
        runtime_report = _write_runtime_tree(
            state, app_dir, proj_base, settings or {}, title,
            package_label="Web HTML", progress=progress,
            bundle_original_images=bundle_original_images,
            copy_audio_assets=False,
            pipeline_log=pipeline_log,
            script_override=script,
            endings_override=endings,
            asset_files_override=asset_files)
        if pipeline_log:
            pipeline_log(
                "web_html.runtime_tree.done",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                app_dir_stats=_quick_path_stats(app_dir),
                image_manifest=_compact_image_manifest_report(
                    runtime_report.get("image_manifest", {})
                    if isinstance(runtime_report, dict) else {}),
            )

        _progress(progress, "Externalizing Web image cache")
        t0 = time.perf_counter()
        if pipeline_log:
            pipeline_log("web_html.image_cache_externalize.start")
        _externalize_web_image_cache(
            app_dir,
            os.path.join(tmp_web_assets_dir, "image_cache"),
            f"{asset_dir_name}/image_cache",
            runtime_report,
        )
        if pipeline_log:
            pipeline_log(
                "web_html.image_cache_externalize.done",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                cache_stats=_image_manifest_cache_quick_stats(
                    os.path.join(tmp_web_assets_dir, "image_cache"),
                    runtime_report.get("image_manifest", {})
                    if isinstance(runtime_report, dict) else {}),
            )

        _progress(progress, "Packaging temporary .pyxapp")
        t0 = time.perf_counter()
        if pipeline_log:
            pipeline_log("web_html.package.start", cwd=tmp)
        try:
            result = subprocess.run(
                [sys.executable, "-m", "pyxel", "package", app_dir,
                 os.path.join(app_dir, "main.py")],
                capture_output=True, text=True, timeout=180, cwd=tmp,
            )
        except subprocess.TimeoutExpired:
            if pipeline_log:
                pipeline_log("web_html.package.timeout",
                             elapsed_sec=round(time.perf_counter() - t0, 4))
            return False, "Web export timed out during pyxapp package (>180s)"
        except Exception as e:
            if pipeline_log:
                pipeline_log("web_html.package.error",
                             elapsed_sec=round(time.perf_counter() - t0, 4),
                             error=str(e))
            return False, str(e)
        if pipeline_log:
            pipeline_log(
                "web_html.package.done",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                returncode=result.returncode,
                stdout_len=len(result.stdout or ""),
                stderr_len=len(result.stderr or ""),
            )
        if result.returncode != 0:
            err = (result.stderr or result.stdout).strip()
            return False, err[:160] if err else "pyxel package failed"

        pyxapp_path = os.path.join(tmp, f"{app_name}.pyxapp")
        if not os.path.exists(pyxapp_path):
            return False, ".pyxapp file not found during Web export"

        _progress(progress, "Converting .pyxapp to HTML")
        t0 = time.perf_counter()
        if pipeline_log:
            pipeline_log(
                "web_html.app2html.start",
                pyxapp_size=_safe_getsize(pyxapp_path),
            )
        try:
            result = subprocess.run(
                [sys.executable, "-m", "pyxel", "app2html", pyxapp_path],
                capture_output=True, text=True, timeout=180, cwd=tmp,
            )
        except subprocess.TimeoutExpired:
            if pipeline_log:
                pipeline_log("web_html.app2html.timeout",
                             elapsed_sec=round(time.perf_counter() - t0, 4))
            return False, "Web export timed out during app2html (>180s)"
        except Exception as e:
            if pipeline_log:
                pipeline_log("web_html.app2html.error",
                             elapsed_sec=round(time.perf_counter() - t0, 4),
                             error=str(e))
            return False, str(e)
        if pipeline_log:
            pipeline_log(
                "web_html.app2html.done",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                returncode=result.returncode,
                stdout_len=len(result.stdout or ""),
                stderr_len=len(result.stderr or ""),
            )
        if result.returncode != 0:
            err = (result.stderr or result.stdout).strip()
            return False, err[:160] if err else "pyxel app2html failed"

        html_path = os.path.join(tmp, f"{app_name}.html")
        if not os.path.exists(html_path):
            return False, "HTML file not found after app2html"

        _progress(progress, "Preparing Web audio assets")
        t0 = time.perf_counter()
        if pipeline_log:
            pipeline_log(
                "web_html.audio_assets.start",
                embed_audio=bool(embed_audio),
                asset_file_count=len(asset_files),
            )
        if embed_audio:
            audio_assets = _audio_asset_data_urls(asset_files, proj_base)
        else:
            audio_assets = _copy_web_audio_assets(
                asset_files, proj_base,
                os.path.join(tmp_web_assets_dir, "audio"),
                f"{asset_dir_name}/audio")
        if pipeline_log:
            pipeline_log(
                "web_html.audio_assets.done",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                audio_asset_count=len(audio_assets),
            )
        loading_url = _copy_web_loading_asset(
            proj_base,
            tmp_web_assets_dir,
            f"{asset_dir_name}/ui",
            pipeline_log=pipeline_log,
        )
        if isinstance(report_out, dict):
            report_out.clear()
            report_out.update(runtime_report or {})

        _progress(progress, "Embedding PVNM viewport")
        _inject_pvnm_viewport(html_path)
        _inject_pvnm_screen_container(html_path)
        _inject_pvnm_loading_overlay(html_path, loading_url)

        t0 = time.perf_counter()
        _progress(progress, "Embedding WebAudio bridge")
        _inject_web_audio_bridge(html_path, audio_assets)
        _progress(progress, "Embedding Web storage bridge")
        _inject_web_storage_bridge(
            html_path, storage_namespace or _web_storage_namespace(app_name))
        _progress(progress, "Embedding Web startup timing bridge")
        _inject_web_startup_bridge(html_path)
        _progress(progress, "Embedding Web input bridge")
        _inject_web_input_bridge(html_path)
        if pipeline_log:
            pipeline_log(
                "web_html.bridges.done",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                html_size=_safe_getsize(html_path),
            )
        _progress(progress, "Externalizing Web pyxapp")
        t0 = time.perf_counter()
        if pipeline_log:
            pipeline_log("web_html.pyxapp_externalize.start")
        _externalize_web_pyxapp(
            html_path,
            os.path.join(tmp_web_assets_dir, "app"),
            f"{asset_dir_name}/app",
            runtime_report,
        )
        if pipeline_log:
            pipeline_log(
                "web_html.pyxapp_externalize.done",
                elapsed_sec=round(time.perf_counter() - t0, 4),
                html_size=_safe_getsize(html_path),
                app_asset_stats=_quick_path_stats(
                    os.path.join(tmp_web_assets_dir, "app")),
            )
        if isinstance(report_out, dict):
            report_out.clear()
            report_out.update(runtime_report or {})
        if local_pyxel_runtime:
            _progress(progress, "Localizing Pyxel Web runtime")
            t0 = time.perf_counter()
            _localize_pyxel_web_runtime(html_path)
            _progress(progress, "Embedding WebView compatibility check")
            _inject_webview_compat_loader(html_path)
            if pipeline_log:
                pipeline_log(
                    "web_html.local_runtime.done",
                    elapsed_sec=round(time.perf_counter() - t0, 4),
                    html_size=_safe_getsize(html_path),
                )
        try:
            t0 = time.perf_counter()
            if pipeline_log:
                pipeline_log("web_html.final_copy.start")
            if os.path.exists(out_path):
                os.remove(out_path)
            shutil.copy2(html_path, out_path)
            final_assets_dir = os.path.join(out_dir, asset_dir_name)
            assets_move_mode = ""
            if os.path.isdir(tmp_web_assets_dir):
                assets_move_mode = _move_path_fast(
                    tmp_web_assets_dir, final_assets_dir)
            elif os.path.exists(final_assets_dir):
                _remove_path(final_assets_dir)
            if local_pyxel_runtime:
                _copy_pyxel_web_runtime(out_dir)
            _copy_export_license_notices(
                out_dir, pipeline_log=pipeline_log,
                event_prefix="web_html.license_notices")
            if pipeline_log:
                img_report = (
                    runtime_report.get("image_manifest", {})
                    if isinstance(runtime_report, dict) else {}
                )
                audio_count = (
                    len(audio_assets) if isinstance(audio_assets, dict) else 0
                )
                pipeline_log(
                    "web_html.final_copy.done",
                    elapsed_sec=round(time.perf_counter() - t0, 4),
                    html_size=_safe_getsize(out_path),
                    final_assets_stats=_quick_path_stats(
                        final_assets_dir,
                        file_count=(
                            int(img_report.get("external_cache_files") or 0)
                            + audio_count + 1
                        )),
                    assets_move_mode=assets_move_mode,
                )
        except Exception as e:
            if pipeline_log:
                pipeline_log("web_html.final_copy.error", error=str(e))
            return False, str(e)
    _progress(progress, "Export complete")
    if pipeline_log:
        pipeline_log("web_html.complete", output_path=os.path.abspath(out_path))
    return True, out_path


