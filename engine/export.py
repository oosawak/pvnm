def _image_manifest_report(manifest: dict) -> dict:
    if not isinstance(manifest, dict):
        return {"ok": False}
    images = manifest.get("images", {})
    palettes = manifest.get("palettes", {})
    external = manifest.get("external_cache", {})
    external_files = 0
    if isinstance(external, dict):
        try:
            external_files = int(external.get("file_count") or 0)
        except Exception:
            external_files = 0
    cache_files: set[str] = set()
    cache_entries = 0
    if isinstance(images, dict):
        for by_path in images.values():
            if not isinstance(by_path, dict):
                continue
            for by_pal in by_path.values():
                if not isinstance(by_pal, dict):
                    continue
                sizes = by_pal.get("sizes", {})
                if not isinstance(sizes, dict):
                    continue
                for entry in sizes.values():
                    if not isinstance(entry, dict):
                        continue
                    cache_entries += 1
                    cache = entry.get("cache")
                    if cache:
                        cache_files.add(str(cache))
    return {
        "ok": True,
        "version": manifest.get("version"),
        "cache_dir": manifest.get("cache_dir", "pvnm_cache"),
        "external_cache": bool(external),
        "external_cache_base": (
            external.get("base_url", "") if isinstance(external, dict) else ""
        ),
        "external_cache_files": external_files,
        "image_keys": len(images) if isinstance(images, dict) else 0,
        "palette_count": len(palettes) if isinstance(palettes, dict) else 0,
        "cache_entry_count": cache_entries,
        "cache_file_count": len(cache_files),
        "cache_files": sorted(cache_files),
    }


def _write_pyxapp_external_asset_dir(
        app_dir: str, asset_dir: str, asset_files: set[str],
        src_base: str, app_name: str, asset_dir_name: str,
        runtime_report: dict | None = None,
        pipeline_log=None) -> dict:
    """Write the sibling asset folder used by portable Linux .pyxapp export."""
    os.makedirs(asset_dir, exist_ok=True)

    t0 = time.perf_counter()
    image_manifest = _move_image_manifest_to_external_assets(
        app_dir, asset_dir, runtime_report)
    if pipeline_log:
        cache_dir_name_for_stats = (
            image_manifest.get("cache_dir", "pvnm_cache")
            if isinstance(image_manifest, dict) else "pvnm_cache"
        )
        pipeline_log(
            "external_assets.image_manifest_moved",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            cache_stats=_image_manifest_cache_quick_stats(
                os.path.join(asset_dir, cache_dir_name_for_stats),
                runtime_report.get("image_manifest", {})
                if isinstance(runtime_report, dict) else {}),
        )

    audio_files = sorted(p for p in asset_files if _is_audio_asset(p))
    copied_audio: list[str] = []
    missing_audio: list[str] = []
    path_map: dict[str, str] = {}
    audio_copy_modes: dict[str, int] = {}
    t_audio = time.perf_counter()
    for rel_path in audio_files:
        src = rel_path if os.path.isabs(rel_path) else os.path.join(src_base, rel_path)
        if not os.path.isfile(src):
            missing_audio.append(str(rel_path))
            continue
        dst_rel = _external_asset_rel_path(rel_path, src_base)
        dst = os.path.join(asset_dir, dst_rel)
        try:
            os.makedirs(os.path.dirname(dst) or asset_dir, exist_ok=True)
            mode = _copy_file_fast(src, dst)
            audio_copy_modes[mode] = audio_copy_modes.get(mode, 0) + 1
            copied_audio.append(str(rel_path))
            path_map[str(rel_path)] = dst_rel
        except Exception as e:
            print(f"[export] external audio skipped ({rel_path}): {e}")
            missing_audio.append(str(rel_path))
    if pipeline_log:
        pipeline_log(
            "external_assets.audio_copied",
            elapsed_sec=round(time.perf_counter() - t_audio, 4),
            audio_asset_count=len(copied_audio),
            audio_copy_modes=audio_copy_modes,
            missing_audio_count=len(missing_audio),
        )

    cache_dir_name = (
        image_manifest.get("cache_dir", "pvnm_cache")
        if isinstance(image_manifest, dict) else "pvnm_cache"
    )
    cache_dir = os.path.join(asset_dir, cache_dir_name)
    t_scan = time.perf_counter()
    cache_files = (
        sorted(name for name in os.listdir(cache_dir) if name.endswith(".npy"))
        if os.path.isdir(cache_dir) else []
    )
    if pipeline_log:
        pipeline_log(
            "external_assets.cache_listed",
            elapsed_sec=round(time.perf_counter() - t_scan, 4),
            image_cache_file_count=len(cache_files),
        )
    report = {
        "version": 1,
        "kind": "pvnm-external-assets",
        "app_name": app_name,
        "asset_dir_name": asset_dir_name,
        "image_manifest": "image_manifest.json",
        "image_prebuild_report": "image_prebuild_report.json",
        "image_prebuild_trace": "image_prebuild_trace.jsonl",
        "cache_dir": cache_dir_name,
        "image_cache_files": cache_files,
        "image_cache_file_count": len(cache_files),
        "audio_assets": copied_audio,
        "audio_asset_count": len(copied_audio),
        "audio_copy_modes": audio_copy_modes,
        "missing_audio_assets": missing_audio,
        "path_map": path_map,
        "runtime_env_override": "PVNM_ASSET_ROOT",
        "note": (
            "Keep this folder next to the .pyxapp, or set PVNM_ASSET_ROOT "
            "to this folder before running pyxel play."
        ),
    }
    t_write = time.perf_counter()
    for name in ("pvnm_external_assets.json", "asset_manifest.json"):
        with open(os.path.join(asset_dir, name), "w", encoding="utf-8") as f:
            json.dump(report, f, ensure_ascii=False, indent=2)
    if pipeline_log:
        pipeline_log(
            "external_assets.manifest_written",
            elapsed_sec=round(time.perf_counter() - t_write, 4),
        )
    return report


def _external_asset_rel_path(path: str, src_base: str) -> str:
    if not os.path.isabs(path):
        return os.path.normpath(path).replace(os.sep, "/")
    try:
        rel = os.path.relpath(os.path.abspath(path), os.path.abspath(src_base))
        if rel == "." or not rel.startswith(".." + os.sep):
            return rel.replace(os.sep, "/")
    except ValueError:
        pass
    digest = hashlib.sha1(os.path.abspath(path).encode("utf-8")).hexdigest()[:16]
    name = os.path.basename(path) or "asset"
    return f"absolute_assets/{digest}/{name}"


def _move_image_manifest_to_external_assets(
        app_dir: str, asset_dir: str,
        runtime_report: dict | None = None) -> dict:
    manifest_path = os.path.join(app_dir, "image_manifest.json")
    prebuild_report_path = os.path.join(app_dir, "image_prebuild_report.json")
    prebuild_trace_path = os.path.join(app_dir, "image_prebuild_trace.jsonl")
    try:
        with open(manifest_path, encoding="utf-8") as f:
            manifest = json.load(f)
    except Exception:
        manifest = {}
    if not isinstance(manifest, dict):
        manifest = {}
    cache_dir_name = str(manifest.get("cache_dir") or "pvnm_cache")
    src_cache_dir = os.path.join(app_dir, cache_dir_name)
    dst_cache_dir = os.path.join(asset_dir, cache_dir_name)

    if os.path.isdir(src_cache_dir):
        if os.path.exists(dst_cache_dir):
            shutil.rmtree(dst_cache_dir)
        _move_path_fast(src_cache_dir, dst_cache_dir)
    elif not os.path.isdir(dst_cache_dir):
        os.makedirs(dst_cache_dir, exist_ok=True)

    if os.path.exists(manifest_path):
        _move_path_fast(manifest_path, os.path.join(asset_dir, "image_manifest.json"))
    else:
        with open(os.path.join(asset_dir, "image_manifest.json"),
                  "w", encoding="utf-8") as f:
            json.dump(manifest, f, ensure_ascii=False, indent=2)

    if os.path.exists(prebuild_report_path):
        _move_path_fast(
            prebuild_report_path,
            os.path.join(asset_dir, "image_prebuild_report.json"))

    if os.path.exists(prebuild_trace_path):
        _move_path_fast(
            prebuild_trace_path,
            os.path.join(asset_dir, "image_prebuild_trace.jsonl"))

    if isinstance(runtime_report, dict):
        report = runtime_report.get("image_manifest")
        if isinstance(report, dict):
            report["external_asset_folder"] = True
            report["embedded_cache_files"] = 0
    return manifest


def _is_audio_asset(path: str) -> bool:
    return os.path.splitext(str(path or ""))[1].lower() in _AUDIO_MIME_BY_EXT


def _audio_asset_data_urls(asset_files: set[str], src_base: str) -> dict[str, str]:
    """Return {runtime_relative_path: data_url} for WebAudio playback."""
    assets: dict[str, str] = {}
    for path in sorted(asset_files):
        if not _is_audio_asset(path):
            continue
        src = path if os.path.isabs(path) else os.path.join(src_base, path)
        if not os.path.exists(src):
            continue
        ext = os.path.splitext(path)[1].lower()
        mime = _AUDIO_MIME_BY_EXT.get(ext, "application/octet-stream")
        key = _export_cache_key_path(path, src_base)
        try:
            with open(src, "rb") as f:
                encoded = base64.b64encode(f.read()).decode("ascii")
            assets[key] = f"data:{mime};base64,{encoded}"
        except Exception as e:
            print(f"[export] WebAudio asset skipped ({path}): {e}")
    return assets


def _quote_url_path(path: str) -> str:
    parts = str(path or "").replace("\\", "/").split("/")
    return "/".join(quote(part) for part in parts if part)


