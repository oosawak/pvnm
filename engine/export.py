def _storage_app_id(app_name: str) -> str:
    raw = str(app_name or "pvnm-game")
    safe = _npm_package_name(raw)
    if safe == "pvnm-game" and raw.strip():
        digest = hashlib.sha1(raw.encode("utf-8")).hexdigest()[:8]
        return f"pvnm-{digest}"
    return safe


