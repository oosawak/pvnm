def _export_capacitor_project_inline(state, output_dir: str,
                                     settings: dict | None = None,
                                     title: str = "My Visual Novel",
                                     progress=None,
                                     bundle_original_images: bool = False,
                                     embed_audio: bool = False,
                                     app_id: str | None = None,
                                     pipeline_log=None
                                     ) -> tuple[bool, str]:
    """Export a Capacitor project skeleton with PVNM Web build in ``www/``."""
    project_dir = os.path.abspath(output_dir)
    app_name = title or os.path.basename(os.path.normpath(project_dir))
    npm_name = _npm_package_name(app_name)
    app_id = app_id or _default_capacitor_app_id(app_name)
    own_pipeline_log = pipeline_log is None
    if pipeline_log is None:
        pipeline_log = _make_export_pipeline_logger(
            "capacitor_project", project_dir, app_name)
    export_started = time.perf_counter()
    pipeline_log(
        "capacitor_project.start",
        output_dir=project_dir,
        app_id=app_id,
        bundle_original_images=bool(bundle_original_images),
        embed_audio=bool(embed_audio),
        source_file=getattr(state, "file_path", "") or "",
    )

    _progress(progress, "Preparing Capacitor project")
    try:
        os.makedirs(project_dir, exist_ok=True)
    except Exception as e:
        pipeline_log("capacitor_project.mkdir.error", error=str(e))
        return False, str(e)

    t0 = time.perf_counter()
    pipeline_log("capacitor_project.web_bundle.start")
    ok, msg = export_web_bundle(
        state,
        os.path.join(project_dir, "www"),
        settings=settings,
        title=app_name,
        progress=progress,
        bundle_original_images=bundle_original_images,
        embed_audio=embed_audio,
        report_out=(runtime_report := {}),
        pipeline_log=pipeline_log,
    )
    if not ok:
        pipeline_log(
            "capacitor_project.web_bundle.error",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            message=msg,
        )
        return False, msg
    pipeline_log(
        "capacitor_project.web_bundle.done",
        elapsed_sec=round(time.perf_counter() - t0, 4),
        runtime_report=_runtime_report_log_summary(runtime_report),
    )

    _progress(progress, "Writing Capacitor files")
    try:
        t0 = time.perf_counter()
        pipeline_log("capacitor_project.files.start")
        proj_base = (os.path.dirname(os.path.abspath(state.file_path))
                     if state.file_path else project_dir)
        script = from_editor_state(state)
        endings = getattr(state, "endings", []) or []
        asset_files = _collect_asset_files(script, endings)
        title_config = _normalize_title_config(getattr(state, "title_config", {}))
        gallery_config = normalize_gallery_config(
            getattr(state, "gallery_config", {}))
        asset_files.update(_collect_title_asset_files(title_config))
        asset_files.update(_collect_gallery_asset_files(gallery_config))
        if embed_audio:
            diagnostic_audio_assets = _audio_asset_data_urls(asset_files, proj_base)
        else:
            diagnostic_audio_assets = _web_audio_asset_urls(
                asset_files, proj_base, "assets/audio")
        _write_web_diagnostics(
            os.path.join(project_dir, "www"),
            _web_storage_namespace(app_name),
            diagnostic_audio_assets,
        )
        _write_web_debug_launcher(
            os.path.join(project_dir, "www"),
            app_name,
        )
        _write_json_file(
            os.path.join(project_dir, "package.json"),
            _capacitor_package_json(npm_name),
        )
        _write_json_file(
            os.path.join(project_dir, "capacitor.config.json"),
            _capacitor_config_json(app_id, app_name),
        )
        _write_text_file(
            os.path.join(project_dir, "README_PVNM_CAPACITOR.md"),
            _capacitor_readme(app_name, app_id),
        )
        build_script = os.path.join(project_dir, "build_android.sh")
        _write_text_file(build_script, _capacitor_build_android_script())
        serve_script = os.path.join(project_dir, "serve_web.sh")
        _write_text_file(serve_script, _capacitor_serve_web_script())
        _write_text_file(
            os.path.join(project_dir, "pvnm_configure_android.py"),
            _capacitor_android_config_script(),
        )
        icon_src = _resolve_packaging_image(
            proj_base, _CUSTOM_APP_ICON, _DEFAULT_APP_ICON)
        icon_size = 0
        if icon_src:
            _copy_file_fast(icon_src, os.path.join(project_dir, "pvnm_app_icon.png"))
            icon_size = _safe_getsize(os.path.join(project_dir, "pvnm_app_icon.png"))
        log_script = os.path.join(project_dir, "android_log.sh")
        _write_text_file(log_script, _capacitor_android_log_script())
        try:
            os.chmod(build_script, 0o755)
            os.chmod(serve_script, 0o755)
            os.chmod(log_script, 0o755)
        except Exception:
            pass
        _write_text_file(
            os.path.join(project_dir, "PVNM_ANDROID_TEST_CHECKLIST.md"),
            _capacitor_android_checklist(app_name),
        )
        _write_text_file(
            os.path.join(project_dir, "PVNM_LOCAL_WEB_CHECK.md"),
            _capacitor_local_web_check(app_name),
        )
        _write_text_file(
            os.path.join(project_dir, "PVNM_ANDROID_NATIVE_CONFIG.md"),
            _capacitor_android_native_config_doc(app_name),
        )
        _write_text_file(
            os.path.join(project_dir, "PVNM_ANDROID_LOGS.md"),
            _capacitor_android_logs_doc(app_name),
        )
        _copy_export_license_notices(
            project_dir, pipeline_log=pipeline_log,
            event_prefix="capacitor_project.license_notices")
        report_path = os.path.join(project_dir, "PVNM_EXPORT_REPORT.md")
        report_args = {
            "app_name": app_name,
            "app_id": app_id,
            "project_dir": project_dir,
            "source_file": getattr(state, "file_path", "") or "",
            "storage_namespace": _web_storage_namespace(app_name),
            "asset_files": asset_files,
            "audio_assets": diagnostic_audio_assets,
            "runtime_report": runtime_report,
            "bundle_original_images": bundle_original_images,
            "embed_audio": embed_audio,
        }
        _write_text_file(report_path, _capacitor_export_report(**report_args))
        _write_gitignore_file(
            os.path.join(project_dir, ".gitignore"),
            _capacitor_gitignore(),
        )
        pipeline_log(
            "capacitor_project.files.done",
            elapsed_sec=round(time.perf_counter() - t0, 4),
            asset_file_count=len(asset_files),
            diagnostic_audio_count=len(diagnostic_audio_assets),
            android_icon_size=icon_size,
            report_size=_safe_getsize(report_path),
        )
    except Exception as e:
        pipeline_log("capacitor_project.files.error", error=str(e))
        return False, str(e)

    _progress(progress, "Export complete")
    pipeline_log(
        "capacitor_project.complete",
        elapsed_sec=round(time.perf_counter() - export_started, 4),
        output_dir=project_dir,
        own_pipeline_log=bool(own_pipeline_log),
    )
    return True, project_dir


